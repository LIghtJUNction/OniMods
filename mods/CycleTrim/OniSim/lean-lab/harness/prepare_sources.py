#!/usr/bin/env python3
"""Extract unchanged project sources and exact disease helpers from the input ZIP."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


LAB = Path(__file__).resolve().parents[1]
ROOT = LAB.parent
ARCHIVE_NAME = "OniSim-source-20261020-040228.zip"
EXPECTED_ARCHIVE_SHA256 = "8c9e01a6033660c92988859d5ab33a278aeefec5ce2c245f63aa087af761e812"
BASELINE = LAB / "baseline"
PREFIX = "mods/CycleTrim/OniSim/native/src/"
FILES = (
    "disease_emitters.rs",
    "fluid_helpers.rs",
    "numeric.rs",
    "status.rs",
    "tables.rs",
    "world_cells.rs",
)
FUNCTIONS = ("clear_disease", "calculate_disease", "add_disease")


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract_function(source: str, name: str) -> tuple[str, int, int]:
    start = source.index(f"pub(crate) fn {name}(")
    brace = source.index("{", start)
    level = 0
    for end in range(brace, len(source)):
        level += (source[end] == "{") - (source[end] == "}")
        if level == 0:
            text = source[start : end + 1]
            first_line = source.count("\n", 0, start) + 1
            last_line = source.count("\n", 0, end) + 1
            return text, first_line, last_line
    raise ValueError(f"unclosed function {name}")


def main() -> None:
    provenance_path = BASELINE / "provenance.json"
    metadata = json.loads(provenance_path.read_text())
    if metadata["archive_sha256"] != EXPECTED_ARCHIVE_SHA256:
        raise ValueError("Baseline archive identity changed")
    for name in FILES:
        data = (BASELINE / name).read_bytes()
        expected = metadata["files"][name]["sha256"]
        actual = digest(data)
        if actual != expected:
            raise ValueError(f"Baseline source changed: {name}: {actual} != {expected}")
    source = (BASELINE / "fluid_helpers.rs").read_text()
    pieces = [
        "// Generated by prepare_sources.py; the function bodies below are verbatim.\n"
        "use crate::tables::DiseaseTable;\n"
        "use crate::world::Cells;\n"
        "use crate::numeric::cvtt_f32_i32 as cvtt;\n"
    ]
    for name in FUNCTIONS:
        text, first_line, last_line = extract_function(source, name)
        pieces.append(text + "\n")
        metadata["functions"][name] = {
            "sha256": digest(text.encode()),
            "first_line": first_line,
            "last_line": last_line,
        }
    output = LAB / "harness/src/disease_helpers.rs"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(pieces))
    generated = output.read_text()
    for name in FUNCTIONS:
        original, _, _ = extract_function(source, name)
        copied, _, _ = extract_function(generated, name)
        assert copied == original, name
    metadata["generated_helpers_sha256"] = digest(output.read_bytes())
    # Baseline metadata is committed and immutable; reruns must not rewrite it.
    if metadata["generated_helpers_sha256"] != digest(output.read_bytes()):
        raise ValueError("Generated disease helper hash changed")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
